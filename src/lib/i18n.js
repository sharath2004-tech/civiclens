export function getAppLanguage() {
  if (typeof window === 'undefined') return 'en';
  return localStorage.getItem('appLanguage') || 'en';
}

export function setAppLanguage(langCode) {
  if (typeof window === 'undefined') return;
  localStorage.setItem('appLanguage', langCode);
  window.dispatchEvent(new CustomEvent('app-language-change', { detail: langCode }));
}

export function useI18n() {
  const [lang, setLang] = React.useState(getAppLanguage);

  React.useEffect(() => {
    const handleLangChange = (e) => {
      setLang(e.detail || getAppLanguage());
    };
    window.addEventListener('app-language-change', handleLangChange);
    return () => window.removeEventListener('app-language-change', handleLangChange);
  }, []);

  const changeLanguage = (code) => {
    setAppLanguage(code);
    setLang(code);
  };

  const t = (key) => {
    return translations[lang]?.[key] || translations.en[key] || key;
  };

  return { lang, changeLanguage, t, supportedLanguages: SUPPORTED_LANGUAGES };
}
